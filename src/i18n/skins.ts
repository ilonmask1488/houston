/** Кто учится — для промптов Claude. */
export const WHO: Record<Field, string> = {
  space: 'инженер (ракетно-космическая техника)',
  mech: 'инженер-механик (машиностроение)',
}

/** Под какую специальность уже применён стиль. */
export let skinField: Field = 'space'

function merge(target: Record<string, unknown>, patch: Record<string, unknown>): void {
  for (const [k, v] of Object.entries(patch)) {
    const cur = target[k]
    if (v && typeof v === 'object' && !Array.isArray(v) && cur && typeof cur === 'object' && !Array.isArray(cur)) merge(cur as Record<string, unknown>, v as Record<string, unknown>)
    else target[k] = v
  }
}

/** Наложить стиль специальности на тексты интерфейса и цвета. Вызывается один раз до отрисовки. */
export function applySkin(field: Field): void {
  skinField = field
  if (field === 'mech') merge(ru as unknown as Record<string, unknown>, MECH as Record<string, unknown>)
  if (typeof document !== 'undefined') {
    if (field === 'space') delete document.documentElement.dataset.field
    else document.documentElement.dataset.field = field
  }
}
